"""Keep the NSIS installer template in step with the Tauri CLI.

``desktop/src-tauri/installer/installer.nsi`` (``bundle.windows.nsis.template``
in tauri.conf.json) is Tauri's own NSIS template with these changes, each
marked "RootMind:" in the file:

- No reinstall page. When the app is installed, Tauri's template asks whether
  to uninstall that version first. RootMind's installer updates it in place
  instead, without questions, the way Tauri's updater does: the installed
  version's uninstaller never runs, app data and shortcuts stay, and the
  installer hooks (installer/hooks.nsh) replace the bundled backend folder.
- No folder page. RootMind installs per machine into
  ``%ProgramFiles%\\RootMind`` only: the installer sets up a LocalSystem
  service from the backend in that folder, which must therefore be admin-only.
  NSIS_HOOK_PREINSTALL refuses any other folder (``/D=``, a changed registry
  value), and ``service install`` refuses a program folder that
  non-administrators can change.
- A header that names the source and the versions.

The template belongs to the tauri-bundler that the locked Tauri CLI uses, so
the file is refreshed with every update of ``@tauri-apps/cli``. This script
reads the CLI version from ``desktop/pnpm-lock.yaml``, the bundler version
from Tauri's Cargo manifests at the tag ``tauri-cli-v<version>``, downloads
that bundler's template and applies the changes at fixed anchors. It fails
when an anchor is missing or no longer unique, so a changed upstream template
is never patched blindly::

    python scripts/nsis_template.py --check   # is the file up to date?
    python scripts/nsis_template.py --write   # refresh it after a Tauri CLI update

Exits 0 when the file is up to date (or was written), 1 when it is not, and 2
on errors (network, a changed upstream template). Needs network access to
raw.githubusercontent.com; standard library only. The offline test
scripts/tests/test_nsis_template.py fails when the header names a CLI version
other than the locked one.
"""

from __future__ import annotations

import argparse
import difflib
import re
import sys
import tomllib
import urllib.request
from collections.abc import Callable
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCKFILE = Path("desktop/pnpm-lock.yaml")
TEMPLATE = Path("desktop/src-tauri/installer/installer.nsi")

RAW_URL = "https://raw.githubusercontent.com/tauri-apps/tauri"
CLI_MANIFEST = "crates/tauri-cli/Cargo.toml"
WORKSPACE_MANIFEST = "Cargo.toml"
UPSTREAM_TEMPLATE = "crates/tauri-bundler/src/bundle/windows/nsis/installer.nsi"

_VERSION = re.compile(r"^[0-9]+\.[0-9]+\.[0-9]+(?:-[0-9A-Za-z.]+)?$")
_LOCKED_CLI = re.compile(
    r"^(?P<indent>[ ]+)'@tauri-apps/cli':\n"
    r"(?P=indent)[ ]+specifier: [^\n]*\n"
    r"(?P=indent)[ ]+version: (?P<version>[^\s(]+)",
    re.MULTILINE,
)
# The header line that names the versions; the offline test reads it.
HEADER_VERSIONS = re.compile(
    r"^; RootMind: the NSIS template of tauri-bundler (?P<bundler>\S+) "
    r"\(@tauri-apps/cli (?P<cli>\S+)\),\r?$",
    re.MULTILINE,
)

# Anchors in the upstream template (whole lines).
REINSTALL_PAGE = "; 4. Custom page to ask user if he wants to reinstall/uninstall"
DIRECTORY_PAGE = "; 5. Choose install directory page"
DIRECTORY_PRE = "!define MUI_PAGE_CUSTOMFUNCTION_PRE SkipIfPassive"
DIRECTORY_MACRO = "!insertmacro MUI_PAGE_DIRECTORY"

# What the patched template must not contain: the reinstall page and its
# state, and the folder page.
FORBIDDEN = (
    "Page custom",
    "PageReinstall",
    "PageLeaveReinstall",
    "ReinstallPageCheck",
    "MUI_PAGE_DIRECTORY",
)
# What it must keep: the installer hooks.
REQUIRED = (
    "{{#if installer_hooks}}",
    '!include "{{installer_hooks}}"',
    "!insertmacro NSIS_HOOK_PREINSTALL",
    "!insertmacro NSIS_HOOK_PREUNINSTALL",
)

HEADER = """\
; RootMind: the NSIS template of tauri-bundler {bundler} (@tauri-apps/cli {cli}),
; https://github.com/tauri-apps/tauri/blob/tauri-bundler-v{bundler}/{path}
; Copyright (c) The Tauri Programme in the Commons Conservancy, Apache-2.0 OR MIT.
; Changes are marked "RootMind:". Generated by scripts/nsis_template.py; run
; "python scripts/nsis_template.py --write" after every Tauri CLI update.
"""

NO_REINSTALL_PAGE = """\
; 4. RootMind: no reinstall page. Tauri's page asks whether to uninstall an
;    installed version first. Instead, the installed version (older, newer or
;    the same as this one) is replaced in place without questions, as Tauri's
;    updater does with /UPDATE: its uninstaller does not run, so app data and
;    shortcuts stay. NSIS_HOOK_PREINSTALL (installer/hooks.nsh) removes the
;    installed $INSTDIR\\backend before the new one is copied, so none of its
;    files are left; the main binary and uninstall.exe are overwritten.
"""

NO_DIRECTORY_PAGE = """\
; 5. RootMind: no install directory page. RootMind installs per machine into
;    $PROGRAMFILES64\\RootMind only: the installer sets up a Windows service
;    that runs as LocalSystem from the backend in that folder, so the folder
;    must be one that only administrators can change. NSIS_HOOK_PREINSTALL
;    (installer/hooks.nsh) refuses any other $INSTDIR, such as one from /D=.
"""


class TemplateError(ValueError):
    """A version that cannot be determined, or an upstream template that no longer fits."""


def locked_cli_version(lockfile: str) -> str:
    """The ``@tauri-apps/cli`` version that ``desktop/pnpm-lock.yaml`` locks."""
    found = {m["version"] for m in _LOCKED_CLI.finditer(lockfile.replace("\r\n", "\n"))}
    if len(found) != 1:
        raise TemplateError(f"expected one locked @tauri-apps/cli version, found {sorted(found)}")
    version = found.pop()
    if not _VERSION.match(version):
        raise TemplateError(f"unexpected @tauri-apps/cli version {version!r}")
    return version


def bundler_version(cli_manifest: str, workspace_manifest: Callable[[], str]) -> str:
    """The tauri-bundler version that tauri-cli's Cargo.toml pins with ``=``.

    ``workspace_manifest`` returns the workspace Cargo.toml; it is read only
    when the CLI takes the dependency from the workspace.
    """
    dependency = tomllib.loads(cli_manifest).get("dependencies", {}).get("tauri-bundler")
    if isinstance(dependency, dict) and dependency.get("workspace") is True:
        workspace = tomllib.loads(workspace_manifest()).get("workspace", {})
        dependency = workspace.get("dependencies", {}).get("tauri-bundler")
    if isinstance(dependency, dict):
        dependency = dependency.get("version")
    if not isinstance(dependency, str):
        raise TemplateError("tauri-cli's Cargo.toml names no tauri-bundler version")
    if not dependency.startswith("=") or not _VERSION.match(dependency[1:]):
        raise TemplateError(f"tauri-cli does not pin one tauri-bundler version: {dependency!r}")
    return dependency[1:]


def _index(lines: list[str], anchor: str) -> int:
    hits = [i for i, line in enumerate(lines) if line == anchor]
    if len(hits) != 1:
        raise TemplateError(
            f"the upstream template has the line {anchor!r} {len(hits)} times, expected once"
        )
    return hits[0]


def render(upstream: str, *, cli: str, bundler: str) -> str:
    """The upstream template with RootMind's changes, as ASCII text with CRLF line endings."""
    lines = upstream.replace("\r\n", "\n").split("\n")

    # 1. The reinstall page: everything from its comment to the directory page.
    start = _index(lines, REINSTALL_PAGE)
    end = _index(lines, DIRECTORY_PAGE)
    page = lines[start:end]
    if (
        end <= start
        or "Page custom PageReinstall PageLeaveReinstall" not in page
        or page[-2:] != ["FunctionEnd", ""]
    ):
        raise TemplateError("the reinstall page of the upstream template has changed")
    lines[start:end] = [*NO_REINSTALL_PAGE.splitlines(), ""]

    # 2. The directory page: its comment, the skip function and the page.
    directory = _index(lines, DIRECTORY_PAGE)
    if lines[directory + 1 : directory + 3] != [DIRECTORY_PRE, DIRECTORY_MACRO]:
        raise TemplateError("the directory page of the upstream template has changed")
    lines[directory : directory + 3] = NO_DIRECTORY_PAGE.splitlines()

    header = HEADER.format(bundler=bundler, cli=cli, path=UPSTREAM_TEMPLATE)
    text = header + "\n" + "\n".join(lines)
    for marker in FORBIDDEN:
        if marker in text:
            raise TemplateError(f"the patched template still contains {marker!r}")
    for marker in REQUIRED:
        if marker not in text:
            raise TemplateError(f"the upstream template no longer contains {marker!r}")
    if not text.isascii():
        raise TemplateError("the upstream template is not ASCII")
    if not text.endswith("\n"):
        text += "\n"
    return text.replace("\n", "\r\n")


def fetch(ref: str, path: str) -> str:
    """A file of the Tauri repository at a tag."""
    url = f"{RAW_URL}/{ref}/{path}"
    with urllib.request.urlopen(url, timeout=60) as response:  # noqa: S310 (fixed https URL)
        return response.read().decode("utf-8")


def build(root: Path, get: Callable[[str, str], str]) -> tuple[str, str, str]:
    """The expected template for the locked CLI: ``(text, cli version, bundler version)``."""
    cli = locked_cli_version((root / LOCKFILE).read_text(encoding="utf-8"))
    cli_tag = f"tauri-cli-v{cli}"
    bundler = bundler_version(get(cli_tag, CLI_MANIFEST), lambda: get(cli_tag, WORKSPACE_MANIFEST))
    upstream = get(f"tauri-bundler-v{bundler}", UPSTREAM_TEMPLATE)
    return render(upstream, cli=cli, bundler=bundler), cli, bundler


def main(
    argv: list[str] | None = None,
    root: Path = ROOT,
    get: Callable[[str, str], str] = fetch,
) -> int:
    parser = argparse.ArgumentParser(
        description="Check or refresh the NSIS installer template for the locked Tauri CLI."
    )
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true", help="exit 1 if the file is out of date")
    mode.add_argument("--write", action="store_true", help="write the file")
    args = parser.parse_args(argv)

    try:
        expected, cli, bundler = build(root, get)
    except (OSError, ValueError, KeyError) as error:
        print(f"nsis_template: {error}", file=sys.stderr)
        return 2
    versions = f"tauri-bundler {bundler}, @tauri-apps/cli {cli}"
    target = root / TEMPLATE

    if args.write:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_bytes(expected.encode("ascii"))
        print(f"Wrote {TEMPLATE.as_posix()} ({versions})")
        return 0

    try:
        current = target.read_bytes().decode("utf-8")
    except (OSError, UnicodeDecodeError):
        current = ""
    want = expected.replace("\r\n", "\n")
    have = current.replace("\r\n", "\n")
    if have == want:
        print(f"{TEMPLATE.as_posix()} is up to date ({versions})")
        return 0
    print(
        f"{TEMPLATE.as_posix()} is not the template of {versions} with RootMind's changes.\n"
        "Refresh it with: python scripts/nsis_template.py --write",
        file=sys.stderr,
    )
    diff = difflib.unified_diff(
        have.splitlines(), want.splitlines(), "committed", "expected", lineterm="", n=1
    )
    for count, line in enumerate(diff):
        if count == 60:
            print("...", file=sys.stderr)
            break
        print(line, file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
